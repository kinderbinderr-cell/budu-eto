"""Build responsive AVIF photos using Pillow with AVIF support.

Run from any directory: python prepare-dish-photos.py [path/to/source-jpg]
The optional JPEG archive supplies less compressed copies of existing photos.
"""

import argparse
import io
import json
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter, ImageOps, ImageStat


ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
OUTPUT = ASSETS / "dishes"
RESAMPLE = Image.Resampling.LANCZOS


def open_photo(path):
    with Image.open(path) as image:
        return ImageOps.exif_transpose(image).convert("RGB")


def source_photo(webp, original):
    if not original.is_file():
        return webp
    jpeg = open_photo(original)
    if min(jpeg.size) < min(webp.size):
        return webp

    # The old archive can contain an earlier photo for a recipe with the same ID.
    sample_size = (64, 64)
    delta = ImageChops.difference(webp.resize(sample_size), jpeg.resize(sample_size))
    if sum(ImageStat.Stat(delta).mean) / 3 > 7:
        return webp
    if abs(jpeg.width / jpeg.height / (webp.width / webp.height) - 1) > 0.02:
        return webp
    return jpeg


def resize(photo, longest_side):
    scale = longest_side / max(photo.size)
    size = tuple(max(1, round(side * scale)) for side in photo.size)
    image = photo.resize(size, RESAMPLE)
    if scale > 1:
        image = image.filter(ImageFilter.UnsharpMask(radius=1.15, percent=45, threshold=3))
    return image


def encode(photo, longest_side, byte_limit, quality):
    image = resize(photo, longest_side)
    while True:
        output = io.BytesIO()
        image.save(output, "AVIF", quality=quality, speed=7, max_threads=1)
        if output.tell() <= byte_limit:
            return image.width, output.getvalue()
        if quality <= 14:
            # Preserve the transfer budget for unusually detailed images.
            if longest_side <= 16:
                raise ValueError(f"AVIF cannot fit in {byte_limit} bytes")
            longest_side = round(longest_side * 0.87)
            image = resize(photo, longest_side)
            quality = 26
        else:
            quality = max(14, quality - (9 if output.tell() > 1.35 * byte_limit else 4))


def prepare(path, originals):
    webp = open_photo(path)
    photo = source_photo(webp, originals / (path.stem + ".jpg")) if originals else webp
    old_bytes = path.stat().st_size
    cover = path.stem == "skillet-cover"
    large = min(1600 if cover else 960, max(720, *photo.size))
    large_width, large_data = encode(photo, large, min(old_bytes, 88 * 1024), 62)
    small = min(640 if cover else 384, max(photo.size))
    small_width, small_data = encode(photo, small, min(old_bytes * 0.55, 18 * 1024), 62)
    (OUTPUT / f"{path.stem}-small.avif").write_bytes(small_data)
    (OUTPUT / f"{path.stem}-large.avif").write_bytes(large_data)
    return path.stem, [small_width, large_width]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("originals", type=Path, nargs="?")
    args = parser.parse_args()
    if args.originals and not args.originals.is_dir():
        parser.error("originals must be an existing directory")

    OUTPUT.mkdir(exist_ok=True)
    paths = sorted(path for path in ASSETS.glob("*.webp") if path.stem != "cuisine-flags")
    with ThreadPoolExecutor(max_workers=8) as workers:
        sizes = dict(workers.map(lambda path: prepare(path, args.originals), paths))
    entries = ",\n".join(f"  {json.dumps(id)}: {json.dumps(widths)}" for id, widths in sizes.items())
    manifest = "// Generated by scripts/prepare-dish-photos.py.\nconst dishPhotoWidths = {\n" + entries + "\n};\n"
    (ROOT / "dish-photos.js").write_text(manifest, encoding="utf-8")
    print(f"Prepared photos for {len(sizes)} assets.")


if __name__ == "__main__":
    main()
